const translationEntries = Object.entries(english).sort(
  ([left], [right]) => right.length - left.length
);

const languageContext = createContext<{
  language: Language;
  setLanguage: (language: Language) => Promise<void>;
}>({
  language: 'fr',
  setLanguage: async () => undefined,
});

let currentLanguage: Language = 'fr';

export async function initializeLanguagePreference(): Promise<Language> {
  const value = await AsyncStorage.getItem(LANGUAGE_STORAGE_KEY);
  currentLanguage = value === 'en' ? 'en' : 'fr';
  return currentLanguage;
}

export function translateText(value: string, language: Language = currentLanguage): string {
  if (language === 'fr') return value;
  const exact = english[value];
  if (exact) return exact;

  let translated = value;
  for (const [french, translatedPhrase] of translationEntries) {
    if (french.length > 3 && translated.includes(french)) {
      translated = translated.split(french).join(translatedPhrase);
    }
  }
  return translated;
}

export function useLanguage() {
  const { language, setLanguage } = useContext(languageContext);
  return useMemo(
    () => ({
      language,
      setLanguage,
      t: (value: string) => translateText(value, language),
    }),
    [language, setLanguage]
  );
}

export function LocalizationProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('fr');
  const selectedByUser = useRef(false);

  useEffect(() => {
    let mounted = true;
    void initializeLanguagePreference()
      .then(value => {
        if (mounted && !selectedByUser.current) setLanguageState(value);
      })
      .catch(error => {
        console.error('Unable to load saved language preference:', error);
        if (mounted && !selectedByUser.current) setLanguageState('fr');
      });
    return () => {
      mounted = false;
    };
  }, []);

  const setLanguage = async (nextLanguage: Language) => {
    await AsyncStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
    selectedByUser.current = true;
    currentLanguage = nextLanguage;
    setLanguageState(nextLanguage);
  };

  currentLanguage = language;
  const contextValue = useMemo(() => ({ language, setLanguage }), [language]);
  return <languageContext.Provider value={contextValue}>{children}</languageContext.Provider>;
}

function translateChildren(children: React.ReactNode, language: Language): React.ReactNode {
  if (typeof children === 'string') return translateText(children, language);
  if (Array.isArray(children)) return children.map(child => translateChildren(child, language));
  if (
    React.isValidElement<{ children?: React.ReactNode; translate?: boolean }>(children)
    && children.props.translate !== false
    && children.props.children !== undefined
  ) {
    return React.cloneElement(children, {
      ...children.props,
      children: translateChildren(children.props.children, language),
    });
  }
  return children;
}

export function LocalizedText({
  children,
  accessibilityLabel,
  accessibilityHint,
  translate = true,
  translateAccessibility = true,
  ...props
}: TextProps & { translate?: boolean; translateAccessibility?: boolean }) {
  const { language } = useLanguage();
  return (
    <NativeText
      {...props}
      accessibilityLabel={accessibilityLabel && translateAccessibility ? translateText(accessibilityLabel, language) : accessibilityLabel}
      accessibilityHint={accessibilityHint && translateAccessibility ? translateText(accessibilityHint, language) : accessibilityHint}
    >
      {translate ? translateChildren(children, language) : children}
    </NativeText>
  );
}

